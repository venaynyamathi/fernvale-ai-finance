def write_answer_key(expected, issues):
    """Human-readable answer key: planted issues + the October 2026 close entries."""
    out = ["# Answer key (private - keep out of the public repo)", "",
           "Generated by `python -m generator.build`. Don't read this before running your "
           "workflows if you want an honest test.", "",
           "## Planted issues", ""]
    for i in issues:
        amt = f" (${i['amount']:,.2f})" if i.get("amount") else ""
        out += [f"### {i['id']} - {i['title']}{amt}", "",
                f"- **Period:** {i['period']}  ", f"- **Area:** {i['area']}  ",
                f"- **What happened:** {i['detail']}  ",
                f"- **How a good workflow finds it:** {i['how_found']}  ",
                f"- **Fix:** {i['fix']}", ""]
    out += ["## October 2026 close - entries the correct books contain", "",
            "These month-end entries are absent from the as-booked ledger (October is open).",
            "", "| Ref | Memo | Debit | Credit | Amount |", "|---|---|---|---|---:|"]
    lines_by_je = {}
    for l in expected.lines:
        lines_by_je.setdefault(l["je_id"], []).append(l)
    for e in expected.entries:
        if e["period"] == "2026-10" and e["entry_kind"] == "month_end" \
                and e["txn_date"] == C.AS_OF:
            ls = lines_by_je[e["je_id"]]
            dr = ", ".join(sorted({f"{l['account_number']} {l['account_name']}" for l in ls
                                   if l["debit"]}))
            cr = ", ".join(sorted({f"{l['account_number']} {l['account_name']}" for l in ls
                                   if l["credit"]}))
            amt = sum(l["debit"] for l in ls)
            out.append(f"| {e['source_ref']} | {e['memo']} | {dr} | {cr} | {amt:,.2f} |")
    (ROOT / "private" / "ANSWER_KEY.md").write_text("\n".join(out) + "\n")


