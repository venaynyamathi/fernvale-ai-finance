def _section(con, name, desc):
    cols = [r[1] for r in con.execute(f"PRAGMA table_info({name})")]
    n = con.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
    return [f"### `{name}`  ({n:,} rows)", "", desc, "", "Columns: " +
            ", ".join(f"`{c}`" for c in cols), ""]


def write_data_dictionary():
    src = sqlite3.connect(ROOT / "data" / "source_systems.sqlite")
    led = sqlite3.connect(ROOT / "build" / "books_as_booked.sqlite")
    out = ["# Data dictionary", "",
           "Generated by `python -m generator.build` from the live schema. Row counts reflect "
           "the current build.", "",
           "## `data/source_systems.sqlite`: the operational systems", ""]
    for title, tables in GROUPS:
        out += [f"## {title}", ""]
        for name, desc in tables.items():
            out += _section(src, name, desc)
    out += ["## `build/books_as_booked.sqlite`: what gets loaded into QuickBooks", "",
            "Opening balances at 2024-11-01, then every transaction through 2026-10-31. Closed "
            "through September 2026; October 2026 is open (no month-end entries yet).", ""]
    for name, desc in LEDGER.items():
        out += _section(led, name, desc)
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "data_dictionary.md").write_text("\n".join(out))
